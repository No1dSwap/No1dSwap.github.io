    function updateLiveRateAndFieldChecks() {
      const ethStr = ethInput.value.trim();
      const noidStr = noidInput.value.trim();

      let ethWei = null;
      if (ethStr) {
        ethWei = decimalToInt(ethStr, 18);
        if (ethWei === null || ethWei <= 0n) {
          ethErr.textContent = "Enter a positive ETH amount (up to 18 decimals).";
          ethInput.setAttribute("aria-invalid", "true");
        } else if (ethWei > SEPOLIA_SPEC.maxEthWei) {
          ethErr.textContent = `Exceeds Sepolia cap of ${SEPOLIA_SPEC.maxEth} ETH.`;
          ethInput.setAttribute("aria-invalid", "true");
        } else {
          ethErr.textContent = "";
          ethInput.removeAttribute("aria-invalid");
        }
      } else {
        ethErr.textContent = "";
        ethInput.removeAttribute("aria-invalid");
      }

      let noidMicro = null;
      if (noidStr) {
        noidMicro = decimalToInt(noidStr, 6);
        if (noidMicro === null || noidMicro <= 0n) {
          noidErr.textContent = "Enter a positive NOID amount (up to 6 decimals).";
          noidInput.setAttribute("aria-invalid", "true");
        } else if (noidMicro > SEPOLIA_SPEC.maxNoidMicro) {
          noidErr.textContent = `Exceeds Sepolia cap of ${formatGroupedDecimal(SEPOLIA_SPEC.maxNoid)} NOID.`;
          noidInput.setAttribute("aria-invalid", "true");
        } else {
          noidErr.textContent = "";
          noidInput.removeAttribute("aria-invalid");
        }
      } else {
        noidErr.textContent = "";
        noidInput.removeAttribute("aria-invalid");
      }

      if (ethWei && ethWei > 0n && noidMicro && noidMicro > 0n) {
        const rate = calculateRate(noidMicro, ethWei);
        if (rate) {
          liveRatePreview.textContent = `Implied rate: ${rate.ethInNoidLabel} · ${rate.noidInEthLabel}`;
        }
      } else {
        liveRatePreview.textContent =
          "Enter Sepolia ETH and NOID amounts to preview the implied exchange rate.";
      }

      const bNoid = bobNoidInput.value.trim();
      if (bNoid) {
        const err = noidAddressProblem(bNoid);
        bobNoidErr.textContent = err ? `Invalid NOID address: ${err}.` : "";
        if (err) bobNoidInput.setAttribute("aria-invalid", "true");
        else bobNoidInput.removeAttribute("aria-invalid");
      } else {
        bobNoidErr.textContent = "";
        bobNoidInput.removeAttribute("aria-invalid");
      }

      const bEth = bobEthInput.value.trim();
      if (bEth) {
        const err = ethAddressProblem(bEth);
        bobEthErr.textContent = err ? `Invalid Ethereum address: ${err}.` : "";
        if (err) bobEthInput.setAttribute("aria-invalid", "true");
        else bobEthInput.removeAttribute("aria-invalid");
      } else {
        bobEthErr.textContent = "";
        bobEthInput.removeAttribute("aria-invalid");
      }
    }

