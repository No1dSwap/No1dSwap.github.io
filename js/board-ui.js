/**
 * Returns true if the decoded offer uses any built-in sample Bob address
 * (either Parano1d `bob_noid` or Ethereum `bob_eth`, case-insensitive).
 * @param {{ bob_noid?: string, bob_eth?: string }} fields
 */
export function usesSampleBobAddress(fields) {
  if (!fields || typeof fields !== "object") return false;
  const bn = typeof fields.bob_noid === "string" ? fields.bob_noid.toLowerCase() : "";
  const be = typeof fields.bob_eth === "string" ? fields.bob_eth.toLowerCase() : "";
  return SAMPLE_BOB_NOID.has(bn) || SAMPLE_BOB_ETH.has(be);
}

