function getToastRegion() {
  let region =
    document.getElementById("toast-region") ||
    document.querySelector(".toast-region");
  if (!region) {
    region = el("div", {
      id: "toast-region",
      className: "toast-region",
      role: "status",
      "aria-live": "polite",
      "aria-atomic": "true",
    });
    document.body.appendChild(region);
  }
  return region;
}

function showToast(message) {
  const region = getToastRegion();
  const toast = el("div", { className: "toast", text: message });
  region.appendChild(toast);
  window.setTimeout(() => {
    if (toast.parentNode) toast.parentNode.removeChild(toast);
  }, 2600);
}

async function copyToClipboard(text) {
  if (
    navigator.clipboard &&
    typeof navigator.clipboard.writeText === "function"
  ) {
    try {
      await navigator.clipboard.writeText(text);
      return true;
    } catch {
      // Fallback below for non-secure or restricted contexts
    }
  }
  try {
    const ta = el("textarea", {
      className: "sr-only",
      "aria-hidden": "true",
      tabindex: "-1",
      readonly: "readonly",
    });
    ta.value = text;
    document.body.appendChild(ta);
    ta.select();
    const ok = document.execCommand("copy");
    document.body.removeChild(ta);
    return ok;
  } catch {
    return false;
  }
}

function flashCopiedButton(btn, originalLabel) {
  if (!btn) return;
  const prevTimer = btn.dataset.copyTimer ? Number(btn.dataset.copyTimer) : 0;
  if (prevTimer) window.clearTimeout(prevTimer);
  btn.classList.add("is-copied");
  btn.textContent = "Copied";
  const timer = window.setTimeout(() => {
    btn.classList.remove("is-copied");
    btn.textContent = originalLabel;
    delete btn.dataset.copyTimer;
  }, 1800);
  btn.dataset.copyTimer = String(timer);
}

async function handleCopyAction(text, btn, originalLabel, toastMessage) {
  const ok = await copyToClipboard(text);
  if (ok) {
    flashCopiedButton(btn, originalLabel);
    showToast(toastMessage);
  } else {
    showToast("Copy blocked by browser — select and copy the code manually.");
  }
}

