function el(tag, attrs = null, children = null) {
  const node = document.createElement(tag);
  if (attrs) {
    for (const [k, v] of Object.entries(attrs)) {
      if (v === undefined || v === null || v === false) continue;
      if (k === "className") {
        node.className = v;
      } else if (k === "text") {
        node.textContent = String(v);
      } else if (k === "hidden") {
        node.hidden = Boolean(v);
      } else if (k === "disabled") {
        node.disabled = Boolean(v);
      } else if (k === "value") {
        node.value = String(v);
      } else if (k === "type") {
        node.type = String(v);
      } else if (k === "on" && typeof v === "object") {
        for (const [ev, handler] of Object.entries(v)) {
          node.addEventListener(ev, handler);
        }
      } else {
        node.setAttribute(k, v === true ? "" : String(v));
      }
    }
  }
  if (children !== null && children !== undefined) {
    const list = Array.isArray(children) ? children : [children];
    for (const child of list) {
      if (child === null || child === undefined || child === false) continue;
      if (typeof child === "string" || typeof child === "number") {
        node.appendChild(document.createTextNode(String(child)));
      } else {
        node.appendChild(child);
      }
    }
  }
  return node;
}

function clearNode(node) {
  while (node.firstChild) {
    node.removeChild(node.firstChild);
  }
}

function isSafeInviteUri(uri) {
  return (
    typeof uri === "string" &&
    uri.startsWith(`${URI_PREFIX}no1dinv1`) &&
    !/[\s\r\n<>"]/.test(uri)
  );
}

function formatUtcTimestamp(isoStr, maxMs = Date.now()) {
  if (!isoStr || typeof isoStr !== "string") return "UTC";
  const parsed = Date.parse(isoStr);
  if (!Number.isFinite(parsed)) return sanitizeDisplayText(isoStr, 32) || "UTC";
  const isFuture = parsed > maxMs;
  const d = new Date(isFuture ? maxMs : parsed);
  const yyyy = String(d.getUTCFullYear()).padStart(4, "0");
  const mm = String(d.getUTCMonth() + 1).padStart(2, "0");
  const dd = String(d.getUTCDate()).padStart(2, "0");
  const hh = String(d.getUTCHours()).padStart(2, "0");
  const min = String(d.getUTCMinutes()).padStart(2, "0");
  const formatted = `${yyyy}-${mm}-${dd} ${hh}:${min} UTC`;
  return isFuture ? `${formatted} (clamped)` : formatted;
}

function parseClampedEpochMs(isoStr, maxMs = Date.now()) {
  const t = Date.parse(isoStr || "");
  if (!Number.isFinite(t)) return 0;
  return Math.min(t, maxMs);
}

function compareBigIntDesc(a, b) {
  if (a === b) return 0;
  return a > b ? -1 : 1;
}

/**
 * Decodes and validates a raw listing object strictly from `offer.code`.
 * Drops any listing whose code fails `decodeInvite()` or uses an unpinned HTLC
 * contract. Never copies amounts, addresses, network, rate, or URI from raw
 * `offer.*` metadata.
 *
 * @param {object} offer
 */
export function resolveOfferForDisplay(offer) {
  if (!offer || typeof offer !== "object" || typeof offer.code !== "string") {
    return null;
  }
  const decoded = decodeInvite(offer.code);
  if (!decoded.ok) return null;
  const pinnedCheck = requirePinnedContract(decoded);
  if (!pinnedCheck.ok || !decoded.contractPinned) return null;

  const isSample =
    Boolean(offer.demo) || SAMPLE_CANONICAL_CODES.has(decoded.canonicalCode);

  return {
    id: typeof offer.id === "string" ? sanitizeDisplayText(offer.id, 48) : "",
    demo: isSample,
    local: Boolean(offer.local) && !isSample,
    postedAtUtc: typeof offer.postedAtUtc === "string" ? offer.postedAtUtc : "",
    observedAtMs:
      typeof offer._observedAtMs === "number" && Number.isFinite(offer._observedAtMs)
        ? offer._observedAtMs
        : Date.now(),
    note:
      typeof offer.note === "string"
        ? sanitizeDisplayText(offer.note, 140)
        : "",
    decoded,
  };
}

