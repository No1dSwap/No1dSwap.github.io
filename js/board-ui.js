function createHandoffModalController() {
  let activeDialog = null;
  let lastTrigger = null;

  function closeModal() {
    if (!activeDialog) return;
    const dlg = activeDialog;
    activeDialog = null;
    if (
      dlg.tagName === "DIALOG" &&
      typeof dlg.close === "function" &&
      dlg.open
    ) {
      dlg.close();
    }
    if (dlg.parentNode) dlg.parentNode.removeChild(dlg);
    if (lastTrigger && typeof lastTrigger.focus === "function") {
      lastTrigger.focus();
    }
    lastTrigger = null;
  }

  function openHandoff(rawCode, triggerBtn) {
    closeModal();
    lastTrigger = triggerBtn || document.activeElement;

    const decoded = decodeInvite(rawCode);
    if (!decoded.ok) {
      showToast("Refused — invitation code could not be decoded.");
      return;
    }
    const pinnedCheck = requirePinnedContract(decoded);
    if (!pinnedCheck.ok || !decoded.contractPinned) {
      showToast("Refused — HTLC contract does not match the pinned address.");
      return;
    }
    if (SAMPLE_CANONICAL_CODES.has(decoded.canonicalCode)) {
      showToast("Desktop handoff is disabled for built-in sample listings.");
      return;
    }
    if (usesSampleBobAddress(decoded.fields)) {
      showToast(SAMPLE_BOB_DISABLED_MSG);
      return;
    }

    // Always rebuild the handoff URI strictly from the canonical decoded code.
    const uriBuilt = buildInviteUri(decoded.canonicalCode);
    if (!uriBuilt.ok || !isSafeInviteUri(uriBuilt.uri)) {
      showToast("Refused — could not build a safe no1d-invite: URI.");
      return;
    }

    const f = decoded.fields;
    const code = decoded.canonicalCode;
    const uri = uriBuilt.uri;

    const titleId = "handoff-modal-title";
    const descId = "handoff-modal-desc";

    const closeBtn = el("button", {
      type: "button",
      className: "modal-close",
      "aria-label": "Close desktop handoff dialog",
      text: "×",
      on: { click: closeModal },
    });

    const head = el("div", { className: "modal-head" }, [
      el("h3", {
        id: titleId,
        className: "modal-title",
        text: "Open in Desktop (no1d-invite:)",
      }),
      closeBtn,
    ]);

    const prefillCallout = el("div", { className: "callout callout-due" }, [
      el("span", {
        className: "callout-title",
        text: BOARD_WARNING,
      }),
      el("p", {
        className: "callout-body",
        text:
          "Pre-fill only: clicking Launch no1d-invite: Link below only pre-fills Alice's New Swap form, identical to pasting the code. It never approves a swap, never sends funds, never starts a step, and never skips the out-of-band 4×4 check-line match. The OS handler lives inside the desktop program.",
      }),
    ]);

    const fallbackGuide = el("p", {
      id: descId,
      text: `Click "Launch no1d-invite: Link" below to hand off to the desktop program, or copy the no1dinv1: code and paste it directly into Alice's New Swap form (required on releases without an OS URI handler; target release ${APP_VERSION}). Verify every amount, address, cap, and the 4×4 check line inside the desktop app.`,
    });

    const summaryRows = [
      el("div", { className: "kv-row" }, [
        el("dt", { text: "Network" }),
        el("dd", { text: `${f.network_label} (chain ${f.chain_id})` }),
      ]),
      el("div", { className: "kv-row" }, [
        el("dt", { text: "Bob gives" }),
        el("dd", {
          className: "num c-eth",
          text: `${formatGroupedDecimal(f.eth_amount)} ETH`,
        }),
      ]),
      el("div", { className: "kv-row" }, [
        el("dt", { text: "Bob wants" }),
        el("dd", {
          className: "num c-noid",
          text: `${formatGroupedDecimal(f.noid_amount)} NOID`,
        }),
      ]),
      el("div", { className: "kv-row" }, [
        el("dt", { text: "HTLC contract" }),
        el("dd", {
          className: "num break-all",
          text: `${f.contract} (v${f.contract_version}, pinned)`,
        }),
      ]),
    ];
    if (decoded.rate && decoded.rate.ethInNoidLabel) {
      summaryRows.push(
        el("div", { className: "kv-row" }, [
          el("dt", { text: "Implied rate" }),
          el("dd", { className: "num", text: decoded.rate.ethInNoidLabel }),
        ]),
      );
    }

    const summaryList = el("dl", { className: "kv-list" }, summaryRows);

    const codeLabel = el("span", {
      className: "form-label",
      text: "Canonical no1dinv1: invitation code (public terms only)",
    });
    const codeBox = el("pre", { className: "modal-code", text: code });

    const reminder = el("p", {
      className: "form-hint",
      text:
        "Never send coins to any address shown on a website. The desktop program reads every term from the code and both chains itself.",
    });

    const body = el("div", { className: "modal-body" }, [
      prefillCallout,
      fallbackGuide,
      summaryList,
      codeLabel,
      codeBox,
      reminder,
    ]);

    const copyBtn = el("button", {
      type: "button",
      className: "btn btn-primary btn-copy",
      text: "Copy no1dinv1: Code",
    });
    copyBtn.addEventListener("click", () => {
      handleCopyAction(
        code,
        copyBtn,
        "Copy no1dinv1: Code",
        "Copied no1dinv1: code — paste into Alice's New Swap form in the desktop app.",
      );
    });

    const launchLink = el("a", {
      href: uri,
      className: "btn btn-amber",
      text: "Launch no1d-invite: Link",
    });

    const doneBtn = el("button", {
      type: "button",
      className: "btn btn-ghost",
      text: "Close",
      on: { click: closeModal },
    });

    const actions = el("div", { className: "modal-actions" }, [
      copyBtn,
      launchLink,
      doneBtn,
    ]);

    const useNativeDialog =
      typeof HTMLDialogElement !== "undefined" &&
      typeof HTMLDialogElement.prototype.showModal === "function";

    if (useNativeDialog) {
      const dialog = el(
        "dialog",
        {
          className: "modal",
          "aria-labelledby": titleId,
          "aria-describedby": descId,
        },
        [head, body, actions],
      );
      dialog.addEventListener("cancel", (ev) => {
        ev.preventDefault();
        closeModal();
      });
      dialog.addEventListener("click", (ev) => {
        if (ev.target === dialog) closeModal();
      });
      document.body.appendChild(dialog);
      activeDialog = dialog;
      dialog.showModal();
      copyBtn.focus();
    } else {
      const card = el(
        "div",
        {
          className: "modal-dialog",
          role: "dialog",
          "aria-modal": "true",
          "aria-labelledby": titleId,
          "aria-describedby": descId,
        },
        [head, body, actions],
      );
      const backdrop = el("div", { className: "modal-backdrop" }, [card]);
      const onKeyDown = (ev) => {
        if (ev.key === "Escape") {
          document.removeEventListener("keydown", onKeyDown);
          closeModal();
        }
      };
      backdrop.addEventListener("click", (ev) => {
        if (ev.target === backdrop) {
          document.removeEventListener("keydown", onKeyDown);
          closeModal();
        }
      });
      document.addEventListener("keydown", onKeyDown);
      document.body.appendChild(backdrop);
      activeDialog = backdrop;
      copyBtn.focus();
    }
  }

  return { openHandoff, closeModal };
}

